'use client';

import React, { useState } from 'react';
import { liveBizBazaarApi } from '@/lib/api/live';
import { setApiMode } from '@/lib/api/client';
import { Card, CardContent } from '@/components/ui/Card';
import { Input } from '@/components/ui/Input';
import { Button } from '@/components/ui/Button';
import { Alert } from '@/components/ui/Alert';

export default function ConnectPage() {
  const [token, setToken] = useState('');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  async function connect(event: React.FormEvent) {
    event.preventDefault();
    setBusy(true);
    setError(null);
    try {
      await liveBizBazaarApi.connect(token);
      setToken('');
      setApiMode('live');
      window.location.assign('/transactions');
    } catch (caught) {
      setError(caught instanceof Error ? caught.message : 'Connection failed');
    } finally {
      setBusy(false);
    }
  }
  return <Card><CardContent className="p-6 max-w-xl space-y-4">
    <h1 className="text-2xl font-bold">Connect local demo session</h1>
    <p className="text-sm text-slate-600">Enter the one-time credential generated by the backend CLI.
      This connects this browser to an isolated demo merchant. It is not public account registration.</p>
    {error && <Alert variant="error" title="Connection failed">{error}</Alert>}
    <form onSubmit={connect} className="space-y-4">
      <Input label="One-time demo credential" type="password" value={token}
        autoComplete="off" required minLength={40} maxLength={100}
        onChange={event => setToken(event.target.value)} />
      <Button type="submit" isLoading={busy}>Connect to backend</Button>
    </form>
  </CardContent></Card>;
}
